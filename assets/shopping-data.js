  var data = window.AURORA_SHOPPING_DATA || {};
  var supermarketList = document.getElementById('supermarketList');
  var souvenirList = document.getElementById('souvenirList');
  if (!supermarketList || !souvenirList) return;

  function esc(value) {
    return String(value == null ? '' : value).replace(/[&<>"']/g, function (c) {
      return {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c];
    });
  }
  function productImage(p) {
    if (!p.image) return '<div class="shopping-product-placeholder" aria-label="官方商品圖待確認"><span>📦</span><small>官方圖<br>待確認</small></div>';
    return '<button class="shopping-product-image-button" type="button" data-product-image="' + esc(p.image) + '" data-product-name="' + esc(p.item) + '" aria-label="放大 ' + esc(p.item) + ' 商品圖"><img class="shopping-product-image" src="' + esc(p.image) + '" alt="' + esc(p.item) + '" loading="lazy" referrerpolicy="no-referrer"><span class="shopping-product-fallback" hidden>📦<small>圖片載入失敗</small></span></button>';
  }
  function richProductRow(p, addButton) {
    return '<div class="shopping-product-row">' +
      productImage(p) +
      '<div class="shopping-product-copy"><b>' + esc(p.item) + '</b><small>' + esc(p.detail || p.reason || '') + '</small>' +
      '<div class="recommend-meta"><span class="recommend-pill">' + esc(p.priority || p.tag || '推薦') + '</span><span class="recommend-pill">' + esc(p.place || '') + '</span></div>' +
      (p.source ? '<a class="shopping-product-source" href="' + esc(p.source) + '" target="_blank" rel="noopener">' + esc(p.sourceLabel || '官方商品頁') + ' ↗</a>' : '') +
      '</div>' +
      (addButton ? '<button class="add-shopping" type="button" data-add-item="' + esc(p.item) + '" data-add-country="奧地利">加入我的清單</button>' : '') +
      '</div>';
  }

